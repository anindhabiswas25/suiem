// Generates typed ABIs for packages/chain from the Foundry artifacts (run after `forge build`).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const out = join(ROOT, "packages", "contracts", "out");
const files: Record<string, string[]> = {
  "demo.ts": ["SuiemDemoVenue", "DemoUSD", "DemoStockToken"],
  "elections.ts": ["SuiemElections"],
};
for (const [file, names] of Object.entries(files)) {
  let body = "// GENERATED by scripts/gen-abis.ts from packages/contracts/out. Do not edit.\n";
  for (const n of names) {
    const abi = JSON.parse(readFileSync(join(out, `${n}.sol`, `${n}.json`), "utf8")).abi;
    body += `\nexport const ${n[0]!.toLowerCase()}${n.slice(1)}Abi = ${JSON.stringify(abi, null, 2)} as const;\n`;
  }
  writeFileSync(join(ROOT, "packages", "chain", "src", "abi", file), body);
  console.log(`wrote ${file}: ${names.join(", ")}`);
}
